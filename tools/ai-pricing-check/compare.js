// Compares the prices found on the pages with the list in
// src/lib/aiPricing.js, and writes the list back. No network, no files: the
// tests run it with small fixtures.

// compare and collectInfo live in src/lib (the extension uses them too)
export { collectInfo, compare } from '../../src/lib/aiPriceMerge.js';

/**
 * Text of the price block for src/lib/aiPricing.js.
 * @param {Array<[string, number, number]>} entries
 * @returns {string}
 */
export function renderBlock(entries) {
  const vendorOf = (prefix) => {
    if (prefix.startsWith('claude')) return 'Anthropic';
    if (/^(llama|gpt-oss|qwen)/.test(prefix)) return 'Groq';
    if (/^(gpt-|chatgpt-|o\d)/.test(prefix)) return 'OpenAI';
    if (prefix.startsWith('gemini')) return 'Google';
    if (/^(mistral|ministral|codestral)/.test(prefix)) return 'Mistral';
    if (prefix.startsWith('deepseek')) return 'DeepSeek';
    return 'Others';
  };
  const order = [
    'Anthropic',
    'OpenAI',
    'Google',
    'Mistral',
    'DeepSeek',
    'Groq',
    'Others',
  ];
  const groups = Object.fromEntries(order.map((name) => [name, []]));
  for (const entry of entries) groups[vendorOf(entry[0])].push(entry);
  const lines = [];
  for (const name of order) {
    if (groups[name].length === 0) continue;
    lines.push(`  // ${name}`);
    for (const [prefix, input, output] of groups[name].sort((a, b) =>
      a[0].localeCompare(b[0]),
    )) {
      lines.push(`  ['${prefix}', ${input}, ${output}],`);
    }
  }
  return lines.join('\n');
}

/**
 * Replaces the marked block in the source of aiPricing.js.
 * @param {string} source
 * @param {string} block
 * @returns {string}
 */
export function replaceBlock(source, block) {
  const pattern =
    /(\/\/ <prices:begin>\r?\n)[\s\S]*?(\r?\n\s*\/\/ <prices:end>)/;
  if (!pattern.test(source)) {
    throw new Error('prices:begin / prices:end markers not found');
  }
  // keep the file's own line endings (CRLF in Windows checkouts)
  const eol = source.includes('\r\n') ? '\r\n' : '\n';
  return source.replace(
    pattern,
    (_, begin, end) => `${begin}${block.replaceAll('\n', eol)}${end}`,
  );
}

/**
 * Source text of src/lib/aiModelInfo.js.
 * @param {Record<string, Record<string, unknown>>} info
 * @returns {string}
 */
export function renderInfoFile(info) {
  const sorted = Object.fromEntries(
    Object.keys(info)
      .sort()
      .map((key) => [key, info[key]]),
  );
  return `// @ts-check
// Details of the models in the price list (aiPricing.js), shown in the tooltip
// of the cheapest-models box on the options page. GENERATED by
// tools/ai-pricing-check (npm run check:prices -- --write) from the providers'
// price pages and OpenRouter's model list -- do not edit by hand.

/**
 * @typedef {object} ModelInfo
 * @property {number} [context] - Context window in tokens.
 * @property {number} [maxOutput] - Largest answer in tokens.
 * @property {string} [released] - Release date, YYYY-MM-DD.
 * @property {string} [modalities] - What the model takes as input.
 * @property {string} [description] - One sentence.
 * @property {number} [cachedInput] - Dollars per million cached input tokens.
 * @property {number} [speed] - Output tokens per second (Groq).
 */

/** @type {Record<string, ModelInfo>} */
export const MODEL_INFO = ${JSON.stringify(sorted, null, 2)};

// The details in use: the built-in ones (MODEL_INFO), or, once the extension
// has read the providers' pages, those it saved (see aiData.js).
/** @type {Record<string, ModelInfo>} */
let current = MODEL_INFO;

/**
 * Replaces the details in use.
 * @param {Record<string, ModelInfo> | null | undefined} map - null brings
 *   back the built-in details.
 */
export function setModelInfo(map) {
  current = map ?? MODEL_INFO;
}

/**
 * @param {string} prefix - A model of the price list.
 * @returns {ModelInfo | null}
 */
export function getModelInfo(prefix) {
  return current[prefix] ?? null;
}
`;
}
